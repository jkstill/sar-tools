declare -A csvFiles=(
	["sar-network-device.xlsx"]="sar-net-dev.csv"
	["sar-network-error-device.xlsx"]="sar-net-ede.csv"
	["sar-network-nfs.xlsx"]="sar-net-nfs.csv"
	["sar-network-nfsd.xlsx"]="sar-net-nfsd.csv"
	["sar-network-socket.xlsx"]="sar-net-sock.csv"
	["sar-context.xlsx"]="sar-context.csv"
	["sar-cpu.xlsx"]="sar-cpu.csv"
	["sar-cpu-combined.xlsx"]="sar-cpu.csv"
	["sar-io-default.xlsx"]="sar-io.csv"
	["sar-io-tps-combined.xlsx"]="sar-io.csv"
