for key in "${!csvFiles[@]}"; do
	value=${csvFiles[$key]}
	echo "$key => $value"
done

for key in "${!csvArgs[@]}"; do
	value=${csvArgs[$key]}
	echo "$key => $value"
done

declare -A fileIsClean

# used to track if LINUX-RESTART and extra header lines have been removed from the source CSV file
# there are some duplicate csv source file names, but that is ok
for csvFile in "${csvFiles[@]}"; do
	fileIsClean["$srcDir/$csvFile"]=0
done

for spreadsheet in "${!csvFiles[@]}"; do
	csvFile=${csvFiles[$spreadsheet]}
	args=${csvArgs[$spreadsheet]}
	
	echo working on $spreadsheet
	[[ -f "$srcDir/$csvFile" ]] || {
		echo "Source CSV file $srcDir/$csvFile not found, skipping $spreadsheet"
		continue	
	}

	[[ -s "$srcDir/$csvFile" ]] || {
		echo "Source CSV file $srcDir/$csvFile is empty, skipping $spreadsheet"
		continue	
	}

	declare -a argsArray=($args)
	# Check if the arguments contain --combined-chart
	if [[ " ${argsArray[@]} " =~ " --combined-chart " ]]; then
		echo "Generating combined chart for $spreadsheet"
	else
		echo "Generating individual charts for $spreadsheet"
	fi

	if [[ fileIsClean["$srcDir/$csvFile"] -eq 0 ]]; then

		grep -Em 1 '(^#\s+hostname|LINUX-RESTART)' "$srcDir/$csvFile" > /dev/null && {

			echo 
			echo "Source CSV file $srcDir/$csvFile has multiple header lines due to LINUX RESTART - cleaning the file to remove extra header lines"
			sed -r -i.bak '/(^#\s+hostname|LINUX-RESTART)/d' "$srcDir/$csvFile"
		
		} 

		fileIsClean["$srcDir/$csvFile"]=1

	fi

	declare -a dynachartCommand=("dynachart.pl" "--spreadsheet-file" "${destDir}/$spreadsheet")
	# Append the arguments to the command array
	dynachartCommand+=("${argsArray[@]}")
	# now execute the command
	sdebug CMD: "${dynachartCommand[@]}  <  $srcDir/$csvFile"
	"${dynachartCommand[@]}" < "$srcDir/$csvFile"

done



