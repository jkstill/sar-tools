	["sar-network-device.xlsx"]="--combined-chart --worksheet-col IFACE --category-col timestamp --chart-cols rxkB/s --chart-cols txkB/s"
	["sar-network-error-device.xlsx"]="--combined-chart --worksheet-col IFACE --category-col timestamp --chart-cols rxerr/s --chart-cols txerr/s"
