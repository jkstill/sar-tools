#!/usr/bin/env bash


usage() {

	cat <<-EOF

	usage: $0 destination-directory

	example script that charts CSV data that has been generated from sar
	Excel XLXS files with charts are produced

	applicable to any CSV data
	
   -d destination-directory
      Directory where the generated Excel files will be placed
      Defaults to ../sar-charts

   -s source-directory
      Directory where the CSV files are located
      Defaults to ./csv

	example: sar-chart.sh -s data-dir

	This script is using data generated by asp.sh

	EOF

}

SAR_DEBUG=${SAR_DEBUG:-0}

sdebug() {
	[[ $SAR_DEBUG -eq 1 ]] && echo "$@"
}

csvHomeDir=${csvHomeDir:-$(pwd)}

cd $csvHomeDir || {
	echo
	echo Cannot access csvHomeDir: $csvHomeDir
	echo
	exit 1
}

sdebug "csvHomeDir: $csvHomeDir"

srcDir='csv'
destDir='sar-charts'

while getopts s:d:h arg
do
	case $arg in
		s) srcDir=$OPTARG;;
		d) destDir=$OPTARG;;
		h) usage;exit 0;;
		*) usage;exit 1;;
	esac

done

cd $srcDir || {
	echo
	echo Cannot access source directory: $srcDir
	echo
	exit 1
}

sdebug "PWD: $(pwd)"
sdebug "srcDir: $srcDir"

cd .. || {
	echo
	echo Cannot access source directory parent: $srcDir
	echo
	exit 1
}

destDir=${destDir:-$(dirname ${srcDir})/sar-charts}

echo Source directory: $srcDir
echo Destination directory: $destDir

[ -d "$srcDir" -a -r "$srcDir" ] || {
	echo
	echo Cannot access "$srcDir"
	echo
	exit 1
}

mkdir -p $destDir

[ -d "$destDir" -a -w "$destDir" ] || {
	echo
	echo cannot read and/or write directory destDir: $destDir
	echo
	usage
	echo
	exit 1
}

